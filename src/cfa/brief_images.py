"""Screenshot the HTML briefs into PNGs plus a briefs/README.md, so they read in the GitHub mobile app.

GitHub shows a folder's README.md with its images inline, so opening briefs/ in the app shows every brief.
Runs on Actions (`brief-images.yml`) after any push that changes briefs/*.html; needs Playwright + Chromium,
which only that workflow installs.

    python -m cfa.brief_images [--all]    # briefs/*.html -> briefs/img/<task>-<n>.png + briefs/README.md

Long pages are cut into several images, since very tall screenshots render blank in some viewers. Only briefs
whose HTML changed since the last run are re-shot (hashes in briefs/img/sources.json), to keep the repo small.
"""
from __future__ import annotations

import argparse
import hashlib
import os

from .brief import BRIEFS, REPO_URL, TITLES, esc
from .common import read_json, write_json

IMG = BRIEFS / "img"
ORDER = ("morning", "news", "weekly", "themes")
WIDTH = 430          # CSS px, a large phone
SCALE = 2            # device pixel ratio, keeps text sharp when zoomed
MAX_WIDTH = 760      # widen up to this so wide tables show whole instead of scrolling off-image
SLICE = 2400         # CSS px per image


def shoot(tasks: list[str]) -> dict[str, list[str]]:
    from playwright.sync_api import sync_playwright

    IMG.mkdir(parents=True, exist_ok=True)
    out: dict[str, list[str]] = {}
    if not tasks:
        return out
    with sync_playwright() as p:
        browser = p.chromium.launch(executable_path=os.environ.get("CHROMIUM_PATH") or None)
        page = browser.new_page(viewport={"width": WIDTH, "height": 900}, device_scale_factor=SCALE,
                                color_scheme="light")
        for task in tasks:
            page.set_viewport_size({"width": WIDTH, "height": 900})
            page.goto((BRIEFS / f"{task}.html").as_uri(), wait_until="load")
            page.add_style_tag(content=".tw{overflow:visible}")
            width = min(MAX_WIDTH, page.evaluate("document.documentElement.scrollWidth"))
            width = max(width, WIDTH)
            if width > WIDTH:
                page.set_viewport_size({"width": width, "height": 900})
            height = page.evaluate("document.documentElement.scrollHeight")
            names = []
            for i, top in enumerate(range(0, height, SLICE), 1):
                name = f"{task}-{i}.png"
                page.screenshot(path=str(IMG / name), full_page=True,
                                clip={"x": 0, "y": top, "width": width, "height": min(SLICE, height - top)})
                names.append(name)
            for f in IMG.glob(f"{task}-*.png"):
                if f.name not in names:
                    f.unlink()
            out[task] = names
        browser.close()
    return out


def readme(images: dict[str, list[str]]) -> str:
    man = read_json(BRIEFS / "manifest.json", {}) or {}
    lines = ["# China fund briefs", "",
             "Screenshots of the latest HTML brief of each scheduled task, for the GitHub mobile app. "
             "Generated by `cfa.brief_images`; don't edit.", ""]
    lines += [f"- [{TITLES[t]}](#{t})" for t in images]
    for task, names in images.items():
        m = man.get(task, {})
        lines += ["", f'<a id="{task}"></a>', "", f"## {TITLES[task]}: {m.get('title', task)}", "",
                  f"{m.get('subtitle', '')} · updated {m.get('generated', '?')} HKT · [HTML]({task}.html)", ""]
        lines += [f"![{esc(TITLES[task])} part {i}](img/{n})" for i, n in enumerate(names, 1)]
    lines += ["", f"Source: [{REPO_URL}]({REPO_URL}). Research signals from public data, not financial advice.", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--all", action="store_true", help="re-shoot every brief, changed or not")
    a = ap.parse_args()
    state = read_json(IMG / "sources.json", {}) or {}
    sha = {t: hashlib.sha256((BRIEFS / f"{t}.html").read_bytes()).hexdigest()
           for t in ORDER if (BRIEFS / f"{t}.html").exists()}
    todo = [t for t in sha if a.all or state.get(t, {}).get("sha") != sha[t]
            or not all((IMG / n).exists() for n in state[t].get("images", []))]
    shot = shoot(todo)
    state = {t: {"sha": sha[t], "images": shot[t] if t in shot else state[t]["images"]} for t in sha}
    write_json(IMG / "sources.json", state)
    (BRIEFS / "README.md").write_text(readme({t: v["images"] for t, v in state.items()}), encoding="utf-8")
    print(f"brief images: re-shot {', '.join(todo) or 'nothing'}; {len(state)} briefs in briefs/README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
